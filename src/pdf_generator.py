
from io import BytesIO
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle
)


def generate_valuation_pdf(vehicle_data, predicted_price):

    buffer = BytesIO()

    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=20 * mm,
        leftMargin=20 * mm,
        topMargin=20 * mm,
        bottomMargin=20 * mm
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Title"],
        fontSize=23,
        textColor=colors.HexColor("#14213D"),
        alignment=TA_CENTER,
        spaceAfter=10
    )

    subtitle_style = ParagraphStyle(
        "Subtitle",
        parent=styles["Normal"],
        fontSize=10,
        alignment=TA_CENTER,
        textColor=colors.grey
    )

    story = []

    # Report heading
    story.append(Paragraph("AutoValue AI", title_style))

    story.append(
        Paragraph(
            "Intelligent Vehicle Valuation Report",
            subtitle_style
        )
    )

    story.append(Spacer(1, 12 * mm))

    # Report information
    story.append(
        Paragraph("VALUATION SUMMARY", styles["Heading2"])
    )

    summary_data = [
        ["Report Generated", datetime.now().strftime("%d-%m-%Y %H:%M")],
        ["Estimated Vehicle Value", f"INR {predicted_price:,.0f}"],
        ["Prediction Model", "Tuned Random Forest Regressor"]
    ]

    summary_table = Table(
        summary_data,
        colWidths=[65 * mm, 95 * mm]
    )

    summary_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#E8EEF5")),
        ("TEXTCOLOR", (0, 0), (-1, -1), colors.HexColor("#14213D")),
        ("FONTNAME", (0, 0), (-1, -1), "Helvetica"),
        ("FONTSIZE", (0, 0), (-1, -1), 10),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.lightgrey),
        ("PADDING", (0, 0), (-1, -1), 9)
    ]))

    story.append(summary_table)
    story.append(Spacer(1, 10 * mm))

    # Vehicle details
    story.append(
        Paragraph("VEHICLE SPECIFICATIONS", styles["Heading2"])
    )

    vehicle = vehicle_data.iloc[0]

    vehicle_fields = [
        ("Brand", "brand"),
        ("Manufacturing Year", "year"),
        ("Kilometres Driven", "km_driven"),
        ("Fuel Type", "fuel"),
        ("Seller Type", "seller_type"),
        ("Transmission", "transmission"),
        ("Ownership", "owner"),
        ("Mileage", "mileage_value"),
        ("Engine Capacity (CC)", "engine_cc"),
        ("Maximum Power (BHP)", "max_power_bhp"),
        ("Torque (Nm)", "torque_nm"),
        ("Seats", "seats")
    ]

    vehicle_table_data = [
        ["Specification", "Vehicle Details"]
    ]

    for label, column in vehicle_fields:

        value = vehicle[column]

        if value is None or str(value).lower() == "nan":
            value = "Not Available"

        vehicle_table_data.append([label, str(value)])

    vehicle_table = Table(
        vehicle_table_data,
        colWidths=[65 * mm, 95 * mm],
        repeatRows=1
    )

    vehicle_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#14213D")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTNAME", (0, 1), (-1, -1), "Helvetica"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.lightgrey),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1),
         [colors.white, colors.HexColor("#F3F6FA")]),
        ("PADDING", (0, 0), (-1, -1), 7)
    ]))

    story.append(vehicle_table)
    story.append(Spacer(1, 10 * mm))

    # Disclaimer
    story.append(
        Paragraph("IMPORTANT DISCLAIMER", styles["Heading2"])
    )

    disclaimer = (
        "This valuation is an estimated price generated by a "
        "machine learning model trained on historical used-car "
        "records. It is not a guaranteed selling price, dealer "
        "quotation or confirmed transaction value. Actual vehicle "
        "value may vary depending on condition, location, service "
        "history, market demand and other factors."
    )

    story.append(Paragraph(disclaimer, styles["BodyText"]))
    story.append(Spacer(1, 10 * mm))

    story.append(
        Paragraph(
            "Generated by AutoValue AI | Academic Machine Learning Project",
            subtitle_style
        )
    )

    document.build(story)

    buffer.seek(0)

    return buffer.getvalue()
